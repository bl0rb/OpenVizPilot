export function normalizeLocale(locale?: string | null): SupportedLocale {
  if (!locale) return DEFAULT_LOCALE;
  const value = locale.toLowerCase();
  if (value.startsWith('de')) return 'de';
  return 'en';
}

export function getCurrentLocale(): SupportedLocale {
  const navigatorLike = globalThis as typeof globalThis & { navigator?: { language?: string } };
  if (typeof navigatorLike.navigator?.language === 'string') {
    return normalizeLocale(navigatorLike.navigator.language);
  }
  return DEFAULT_LOCALE;
}

export function t(key: string, locale?: string | null, params?: Record<string, string | number>): string {
  const activeLocale = normalizeLocale(locale ?? getCurrentLocale());
  const message = MESSAGES[activeLocale][key] ?? MESSAGES[DEFAULT_LOCALE][key] ?? key;
  if (!params) return message;
  return message.replace(/\{(\w+)\}/g, (_match, name) => {
    const value = params[name];
    return value === undefined ? '' : String(value);
  });
}
